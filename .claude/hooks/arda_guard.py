#!/usr/bin/env python3
"""A.R.D.A. guard hooks for Claude Code.

Core file generated by daeron-core: do not edit here (changes are reported as drift).
Usage: arda_guard.py <check>  (reads the hook event JSON from stdin)
Exit 2 blocks the action and shows the message to the agent.
"""
import json
import os
import re
import shlex
import subprocess
import sys
from pathlib import Path

ROOT = Path(os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd()).resolve()
SPECS_DIR = "docs/specs/"
ACTIVE_SPEC = ".arda/active-spec"
FREE_PATHS = ("docs/", "spikes/", ".arda/active-spec", ".arda/review.diff")  # spikes/: throwaway prototypes, never merged
WRITE_TOOLS = {"Edit", "Write", "MultiEdit", "NotebookEdit"}

TEST_RE = re.compile(r"(^|/)(tests?|__tests__)/|(^|/)test_[^/]+$|[._-](test|spec)\.[A-Za-z0-9]+$|_test\.[A-Za-z0-9]+$")
SECRET_NAME_RE = re.compile(
    r"(^|/)\.env(\.(?!example$|sample$|template$)[^/]+)?$"
    r"|\.(pem|key|p12|pfx|jks|keystore)$"
    r"|(^|/)id_(rsa|dsa|ecdsa|ed25519)(\.pub)?$"
    r"|(^|/)(credentials|secrets?)\.(json|ya?ml|toml|ini|txt|env)$"
    r"|(^|/)secrets?/"
)
APPROVED_RE = re.compile(r"^status:\s*approved\b", re.MULTILINE)
DANGEROUS = [
    (re.compile(r"\brm\s+(-[A-Za-z]*r[A-Za-z]*f[A-Za-z]*|-[A-Za-z]*f[A-Za-z]*r[A-Za-z]*|-r\s+-f|-f\s+-r|--recursive\s+--force|--force\s+--recursive)\s+(/|/\*|~|~/|\.|\./|\.\.|\*|\$HOME)(\s|;|$)"), "recursive forced delete of a broad target"),
    (re.compile(r"\bgit\s+push\b[^;&|]*(\s--force(\s|$)|\s-f(\s|$)|\s\+[^\s]+)"), "force push"),
    (re.compile(r"\bgit\s+push\b[^;&|]*[\s:](main|master)(\s|$)"), "direct push to the main branch (use a PR)"),
    (re.compile(r"\bgit\s+reset\b[^;&|]*--hard"), "git reset --hard"),
    (re.compile(r"\bgit\s+clean\b[^;&|]*\s-[A-Za-z]*f"), "git clean -f"),
    (re.compile(r"\bgit\s+(filter-branch|filter-repo)\b"), "history rewrite"),
    (re.compile(r"\b(curl|wget)\b[^|;&]*\|\s*(sudo\s+)?(ba|z|da)?sh\b"), "piping a download into a shell"),
    (re.compile(r"\bchmod\s+-R\s+777\b"), "chmod -R 777"),
    (re.compile(r"\bmkfs(\.|\s)|\bdd\b[^;&|]*\bof=/dev/"), "writing to a block device"),
]
WRITE_CMD_RE = re.compile(r"\bsed\s+-[A-Za-z]*i|\bperl\s+-[A-Za-z]*i|>|\btee\b|\bpython3?\b|\bawk\s+-i|\bcp\b|\bmv\b")


def deny(message):
    print(f"A.R.D.A.: {message}", file=sys.stderr)
    sys.exit(2)


def rel(path):
    if not path:
        return ""
    p = Path(path)
    if not p.is_absolute():
        p = ROOT / p
    try:
        return p.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return None  # outside the project


def frontmatter(text):
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end < 0:
        return {}
    data = {}
    for line in text[3:end].splitlines():
        if ":" in line and not line.lstrip().startswith("#"):
            key, value = line.split(":", 1)
            data[key.strip()] = value.split("#", 1)[0].strip().strip("\"'")
    return data


def read_fm(rel_path):
    p = ROOT / rel_path
    return frontmatter(p.read_text(encoding="utf-8")) if p.is_file() else None


def active_spec():
    p = ROOT / ACTIVE_SPEC
    if not p.is_file():
        return None, None
    spec = p.read_text(encoding="utf-8").strip()
    return spec, read_fm(spec)


def written_texts(ti):
    texts = [ti.get(k) for k in ("content", "new_string", "new_source")]
    texts += [e.get("new_string") for e in ti.get("edits") or [] if isinstance(e, dict)]
    return [t for t in texts if isinstance(t, str)]


def target(ti):
    return ti.get("file_path") or ti.get("notebook_path") or ti.get("path") or ""


def check_require_approved_spec(tool, ti):
    if tool not in WRITE_TOOLS:
        return
    path = rel(target(ti))
    if path is None or path.startswith(FREE_PATHS) or path in FREE_PATHS:
        return
    spec, fm = active_spec()
    if not spec:
        deny(f"no active spec. Principle 0: refine a spec, get it approved (/decidir) and set {ACTIVE_SPEC} before editing {path}.")
    if fm is None:
        deny(f"active spec '{spec}' does not exist.")
    if fm.get("status") != "approved":
        deny(f"active spec '{spec}' is '{fm.get('status')}', not 'approved'. Only approved specs can be implemented.")


def check_protect_approval(tool, ti):
    if tool == "Bash":
        cmd = ti.get("command", "")
        if re.search(r"status:\s*approved", cmd) and WRITE_CMD_RE.search(cmd):
            deny("only a person can approve a spec (status: approved).")
        return
    if tool not in WRITE_TOOLS:
        return
    path = rel(target(ti))
    if not path or not path.startswith(SPECS_DIR) or not path.endswith(".md"):
        return
    current = read_fm(path)
    if current and current.get("status") == "approved":
        old, new = ti.get("old_string"), ti.get("new_string")
        if tool == "Edit" and isinstance(old, str) and "status: approved" in old and new == old.replace("status: approved", "status: implemented"):
            return
        deny(f"'{path}' is approved and immutable for agents. If it must change, ask the owner to set it back to 'draft' (back to Refinar).")
    if any(APPROVED_RE.search(t) for t in written_texts(ti)):
        deny("only a person can approve a spec (status: approved).")


def check_protect_tests(tool, ti):
    if tool not in WRITE_TOOLS:
        return
    path = rel(target(ti))
    if not path or path.startswith("docs/") or not TEST_RE.search(path):
        return
    if tool == "Write" and not (ROOT / path).exists():
        return  # creating a new test is allowed (test-first)
    spec, fm = active_spec()
    if fm and fm.get("test_changes") in ("allowed", "true", "yes"):
        return
    deny(f"'{path}' is an existing test: tests are the oracle and cannot be changed unless the approved spec sets 'test_changes: allowed'.")


def check_protect_secrets(tool, ti):
    if tool == "Bash":
        try:
            tokens = shlex.split(ti.get("command", ""))
        except ValueError:
            tokens = ti.get("command", "").split()
        for tok in tokens:
            for part in re.split(r"[=<>|;&]", tok):
                if part and SECRET_NAME_RE.search(part.strip()):
                    deny(f"command touches a secrets file ('{part}'). Secrets are off-limits for agents.")
        return
    path = target(ti)
    if path and SECRET_NAME_RE.search(Path(path).as_posix()):
        deny(f"'{path}' looks like a secrets file. Secrets are off-limits for agents.")


def check_deny_dangerous(tool, ti):
    if tool != "Bash":
        return
    cmd = ti.get("command", "")
    for pattern, reason in DANGEROUS:
        if pattern.search(cmd):
            deny(f"blocked dangerous command ({reason}). Ask the owner to run it if it is really needed.")


def check_stop_checks(data):
    if data.get("stop_hook_active"):
        return
    script = ROOT / ".arda" / "checks.sh"
    if not script.is_file():
        return
    try:
        res = subprocess.run(["bash", str(script)], cwd=ROOT, capture_output=True, text=True, timeout=600)
    except subprocess.TimeoutExpired:
        deny("project checks (.arda/checks.sh) timed out.")
    if res.returncode != 0:
        tail = "\n".join((res.stdout + res.stderr).splitlines()[-60:])
        deny(f"project checks failed (.arda/checks.sh). Fix them before finishing:\n{tail}")


CHECKS = {
    "require-approved-spec": check_require_approved_spec,
    "protect-approval": check_protect_approval,
    "protect-tests": check_protect_tests,
    "protect-secrets": check_protect_secrets,
    "deny-dangerous": check_deny_dangerous,
}


def main():
    if len(sys.argv) != 2:
        print("usage: arda_guard.py <check>", file=sys.stderr)
        sys.exit(1)
    raw = sys.stdin.read()
    try:
        data = json.loads(raw) if raw.strip() else {}
    except json.JSONDecodeError:
        deny("invalid hook input.")
    name = sys.argv[1]
    if name == "stop-checks":
        check_stop_checks(data)
    elif name in CHECKS:
        CHECKS[name](data.get("tool_name", ""), data.get("tool_input") or {})
    else:
        print(f"unknown check: {name}", file=sys.stderr)
        sys.exit(1)
    sys.exit(0)


if __name__ == "__main__":
    main()
