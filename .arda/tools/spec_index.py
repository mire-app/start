#!/usr/bin/env python3
"""Regenerates docs/specs/index.md from the frontmatter of specs and decisions.

Core file generated by daeron-core: do not edit here (changes are reported as drift).
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SECTIONS = [("Specs", ROOT / "docs" / "specs"), ("Decisiones (ADR)", ROOT / "docs" / "decisions")]
SKIP = {"_template.md", "index.md", "README.md"}


def frontmatter(text):
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    data = {}
    for line in text[3:end].splitlines() if end > 0 else []:
        if ":" in line:
            k, v = line.split(":", 1)
            data[k.strip()] = v.split("#", 1)[0].strip().strip("\"'")
    return data


def main():
    out = ["# Índice de conocimiento", "",
           "> Generado por `.arda/tools/spec_index.py`. No editar a mano: ejecutar `python3 .arda/tools/spec_index.py`.", ""]
    for title, folder in SECTIONS:
        out += [f"## {title}", "", "| ID | Título | Estado | Resumen | Fichero |", "|---|---|---|---|---|"]
        rows = 0
        for f in sorted(folder.glob("*.md")) if folder.is_dir() else []:
            if f.name in SKIP:
                continue
            fm = frontmatter(f.read_text(encoding="utf-8"))
            link = f.name if folder.name == "specs" else f"../decisions/{f.name}"
            out.append(f"| {fm.get('id', '?')} | {fm.get('title', f.stem)} | {fm.get('status', '?')} | {fm.get('summary', '')} | [{f.name}]({link}) |")
            rows += 1
        if not rows:
            out.append("| — | — | — | — | — |")
        out.append("")
    target = ROOT / "docs" / "specs" / "index.md"
    target.write_text("\n".join(out), encoding="utf-8")
    print(f"written {target.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
