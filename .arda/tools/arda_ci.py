#!/usr/bin/env python3
"""A.R.D.A. CI checks (GitHub Actions).

Core file generated by daeron-core: do not edit here (changes are reported as drift).
Usage: arda_ci.py gate|secrets|manifest|checks
"""
import hashlib
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path.cwd()
FREE_PATHS = ("docs/", ".arda/active-spec")
SPEC_REF_RE = re.compile(r"\bSPEC-[0-9]{4}\b")
STRUCTURE_RE = re.compile(r"Structure:\s*daeron-core\s+v?([0-9]+\.[0-9]+\.[0-9]+)")
SECRET_NAME_RE = re.compile(
    r"(^|/)\.env(\.(?!example$|sample$|template$)[^/]+)?$|\.(pem|key|p12|pfx|jks|keystore)$"
    r"|(^|/)id_(rsa|dsa|ecdsa|ed25519)$|(^|/)(credentials|secrets?)\.(json|ya?ml|toml|ini|txt|env)$"
)
SECRET_CONTENT = [
    (re.compile("AKIA" + r"[0-9A-Z]{16}"), "AWS access key"),
    (re.compile("-----BEGIN " + r"([A-Z]+ )?PRIVATE KEY-----"), "private key"),
    (re.compile("gh" + r"[pousr]_[A-Za-z0-9]{36,}"), "GitHub token"),
    (re.compile("xox" + r"[baprs]-[A-Za-z0-9-]{10,}"), "Slack token"),
    (re.compile("sk-" + r"(ant-|proj-)?[A-Za-z0-9_-]{32,}"), "API secret key"),
    (re.compile(r"(?i)\b(api[_-]?key|secret|token|password|passwd)\b\s*[:=]\s*['\"][^'\"\s]{12,}['\"]"), "hard-coded credential"),
]


def fail(msg):
    print(f"::error::{msg}")
    sys.exit(1)


def event():
    path = os.environ.get("GITHUB_EVENT_PATH")
    return json.loads(Path(path).read_text()) if path and Path(path).is_file() else {}


def changed_files():
    pr = event().get("pull_request") or {}
    base, head = (pr.get("base") or {}).get("sha"), (pr.get("head") or {}).get("sha")
    rng = f"{base}...{head}" if base and head else "HEAD~1...HEAD"
    out = subprocess.run(["git", "diff", "--name-only", "--diff-filter=ACMR", rng], capture_output=True, text=True, check=True)
    return [l for l in out.stdout.splitlines() if l]


def frontmatter(text):
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    data = {}
    for line in text[3:end].splitlines() if end > 0 else []:
        if ":" in line:
            k, v = line.split(":", 1)
            data[k.strip()] = v.split("#", 1)[0].strip().strip("\"'")
    return data


def specs_by_id():
    found = {}
    for f in (ROOT / "docs" / "specs").glob("*.md"):
        fm = frontmatter(f.read_text(encoding="utf-8"))
        if fm.get("id"):
            found[fm["id"]] = (f, fm)
    return found


def cmd_gate():
    files = changed_files()
    spikes = [f for f in files if f.startswith("spikes/")]
    if spikes:
        fail(f"spikes/ are throwaway prototypes and are never merged: {', '.join(spikes[:5])}")
    code = [f for f in files if not f.startswith(FREE_PATHS)]
    if not code:
        print("Only documentation/specs changed: no spec reference required.")
        return
    body = (event().get("pull_request") or {}).get("body") or ""
    manifest = load_manifest()
    generated = {f["path"] for f in manifest.get("files", [])} | {".arda/manifest.yaml"}
    if manifest and all(f in generated for f in code):
        m = STRUCTURE_RE.search(body)
        if not m:
            fail("This PR only changes A.R.D.A. structure files: declare 'Structure: daeron-core vX.Y.Z' in the description.")
        if m.group(1) != manifest.get("daeron_core_version"):
            fail(f"PR declares daeron-core v{m.group(1)} but the manifest says v{manifest.get('daeron_core_version')}.")
        print(f"Structure gate passed: {len(code)} file(s) generated by daeron-core v{m.group(1)} (authorised by the approved design in daeron-core).")
        return
    refs = sorted(set(SPEC_REF_RE.findall(body)))
    if not refs:
        fail("This PR changes code but references no spec. Add 'Spec: SPEC-NNNN' to the PR description (Principle 0).")
    specs = specs_by_id()
    for ref in refs:
        if ref not in specs:
            fail(f"{ref} is referenced but does not exist in docs/specs/.")
        status = specs[ref][1].get("status")
        if status not in ("approved", "implemented"):
            fail(f"{ref} is '{status}': only approved specs can be implemented.")
    print(f"Spec gate passed: {', '.join(refs)} approved for {len(code)} changed file(s).")


def load_manifest():
    m = ROOT / ".arda" / "manifest.yaml"
    if not m.is_file():
        return {}
    try:
        import yaml
    except ImportError:
        fail("PyYAML is required to read .arda/manifest.yaml (pip install pyyaml).")
    return yaml.safe_load(m.read_text()) or {}


def core_exact():
    return {f["path"] for f in load_manifest().get("files", []) if f.get("owner") == "core"}


def cmd_secrets():
    skip = core_exact()
    findings = []
    for f in changed_files():
        if SECRET_NAME_RE.search(f):
            findings.append(f"{f}: secrets file must not be committed")
            continue
        if f in skip or not (ROOT / f).is_file():
            continue
        try:
            text = (ROOT / f).read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        for n, line in enumerate(text.splitlines(), 1):
            for pattern, label in SECRET_CONTENT:
                if pattern.search(line):
                    findings.append(f"{f}:{n}: possible {label}")
    if findings:
        for x in findings:
            print(f"::error::{x}")
        sys.exit(1)
    print("Secret scan passed.")


def cmd_manifest():
    data = load_manifest()
    if not data:
        print("::warning::.arda/manifest.yaml not found.")
        return
    drift = 0
    for f in data.get("files", []):
        if f.get("owner") != "core":
            continue
        p = ROOT / f["path"]
        if not p.is_file():
            print(f"::warning file={f['path']}::core file missing (A.R.D.A. drift).")
            drift += 1
        elif hashlib.sha256(p.read_bytes()).hexdigest() != f.get("sha256"):
            print(f"::warning file={f['path']}::core file modified (A.R.D.A. drift). Move the change to a project file or report it to daeron-core.")
            drift += 1
    print(f"Manifest check: {drift} drifted core file(s).")


def cmd_checks():
    script = ROOT / ".arda" / "checks.sh"
    if not script.is_file():
        print("No project checks defined (.arda/checks.sh).")
        return
    sys.exit(subprocess.run(["bash", str(script)], cwd=ROOT).returncode)


if __name__ == "__main__":
    cmds = {"gate": cmd_gate, "secrets": cmd_secrets, "manifest": cmd_manifest, "checks": cmd_checks}
    if len(sys.argv) != 2 or sys.argv[1] not in cmds:
        print(__doc__)
        sys.exit(2)
    cmds[sys.argv[1]]()
